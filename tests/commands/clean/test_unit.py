import argparse
import os
import shutil
import tempfile

from sinol_make.commands.clean import Command
from tests import util


def _create_package(tmpdir):
    package_path = os.path.join(tmpdir, "hwr")
    shutil.copytree(util.get_handwritten_package_path(), package_path)
    os.chdir(package_path)

    util.create_ins_outs(package_path)

    return Command()


def test_clean_tests():
    """
    Test removing tests generated by ingen.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        command = _create_package(tmpdir)

        assert set(os.listdir("in")) == {
            "hwr0.in",
            "hwr0a.in",
            "hwr1a.in",
            "hwr2a.in",
        }

        command.run(argparse.Namespace(
            tests=True,
            cache=False,
        ))

        assert set(os.listdir("in")) == {
            "hwr0.in",
            "hwr0a.in",
        }
        assert set(os.listdir("out")) == {
            "hwr0.out",
            "hwr0a.out",
        }

        # --tests should not remove cache.
        assert os.path.exists(".cache")


def test_clean_cache():
    """
    Test removing cache without removing tests.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        command = _create_package(tmpdir)

        inputs_before = set(os.listdir("in"))
        outputs_before = set(os.listdir("out"))

        assert os.path.exists(".cache")

        command.run(argparse.Namespace(
            tests=False,
            cache=True,
        ))

        assert not os.path.exists(".cache")
        assert set(os.listdir("in")) == inputs_before
        assert set(os.listdir("out")) == outputs_before


def test_clean_without_flags():
    """
    Test that clean without flags removes generated tests and cache.
    """
    with tempfile.TemporaryDirectory() as tmpdir:
        command = _create_package(tmpdir)

        command.run(argparse.Namespace(
            tests=False,
            cache=False,
        ))

        assert set(os.listdir("in")) == {
            "hwr0.in",
            "hwr0a.in",
        }
        assert set(os.listdir("out")) == {
            "hwr0.out",
            "hwr0a.out",
        }
        assert not os.path.exists(".cache")
