import argparse
import os
import shutil

from sinol_make import util
from sinol_make.commands.ingen.ingen_util import generate_input_tests, get_generated_tests
from sinol_make.helpers import compiler, package_util, paths
from sinol_make.interfaces.BaseCommand import BaseCommand


class Command(BaseCommand):
    """
    Class for `clean` command.
    """

    def get_name(self):
        return "clean"

    def configure_subparser(self, subparser):
        parser = subparser.add_parser(
            self.get_name(),
            help="Remove generated files",
            description="Remove tests generated by ingen and/or sinol-make cache."
        )
        parser.add_argument(
            "--tests",
            action="store_true",
            help="remove tests generated by ingen",
        )
        parser.add_argument(
            "--cache",
            action="store_true",
            help="remove the .cache directory",
        )
        return parser

    def clean_tests(self):
        temp_dir = paths.get_cache_path("clean", "tests")
        ingen_args = compiler.get_default_compilers()
        ingen_args.compile_mode = "default"
        ingen_args.sanitize = "no"
        generate_input_tests(self.task_id, ingen_args, temp_dir)
        generated_tests = get_generated_tests(self.task_id, temp_dir)

        removed = 0
        for test_id in generated_tests:
            for ext in ("in", "out"):
                test_path = os.path.join(
                    ext,
                    f"{self.task_id}{test_id}.{ext}",
                )
                if os.path.isfile(test_path):
                    os.remove(test_path)
                    removed += 1

        print(util.info(f"Removed {removed} generated test file(s)."))

    def clean_cache(self):
        cache_dir = paths.get_cache_path()
        if os.path.exists(cache_dir):
            shutil.rmtree(cache_dir)
        print(util.info("Removed cache."))

    def run(self, args: argparse.Namespace):
        args = util.init_package_command(args)

        clean_tests = args.tests
        clean_cache = args.cache
        # With no flags, clean everything.
        if not clean_tests and not clean_cache:
            clean_tests = True
            clean_cache = True

        if clean_tests:
            self.task_id = package_util.get_task_id()
            util.change_stack_size_to_unlimited()
            self.clean_tests()

        # Cache has to be removed last. clean_tests uses it.
        if clean_cache:
            self.clean_cache()

